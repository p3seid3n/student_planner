// Generates src/components/icons.gen.ts from Material Symbols (Rounded) so only
// the icons the app uses end up in the bundle. Run: node scripts/gen-icons.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const names = `home calendar_month calendar_today school task_alt check_circle radio_button_unchecked settings add close
chevron_left chevron_right keyboard_arrow_down keyboard_arrow_up today event schedule location_on person edit delete more_vert sync
cloud_download upload_file download link palette dark_mode light_mode contrast award_star trending_up trending_down
assignment quiz notifications desktop_windows fullscreen fullscreen_exit arrow_back search filter_list view_day
view_week calendar_view_month view_agenda check undo info warning error stars calculate timer content_paste
open_in_new visibility visibility_off merge bolt coffee celebration wb_sunny bedtime keyboard menu_book science
functions translate sports_soccer brush music_note public history_edu computer psychology add_task event_note
edit_calendar star restart_alt eco account_balance payments target lightbulb hourglass_top done_all inventory_2
bookmark sentiment_satisfied keep timeline backup tune format_paint apps rocket_launch theater_comedy groups
arrow_forward lock_open dock_to_right swipe touch_app drag_pan`.split(/\s+/).filter(Boolean);

const FILLED = new Set(['home','calendar_month','school','task_alt','settings','check_circle','star','visibility','award_star','desktop_windows','event','quiz','assignment','bookmark']);
const base = 'node_modules/@material-symbols/svg-400/rounded';
const out = {};
for (const n of names) {
  for (const variant of FILLED.has(n) ? ['', '-fill'] : ['']) {
    const f = `${base}/${n}${variant}.svg`;
    if (!existsSync(f)) {
      if (!variant) console.warn('missing icon', n);
      continue;
    }
    const svg = readFileSync(f, 'utf8');
    const d = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(' ');
    out[n + (variant ? '_fill' : '')] = d;
  }
}
const body = Object.entries(out)
  .map(([k, v]) => `  ${k}: '${v}',`)
  .join('\n');
writeFileSync(
  'src/components/icons.gen.ts',
  `// AUTO-GENERATED by scripts/gen-icons.mjs — Material Symbols Rounded (Apache 2.0)\nexport const ICONS: Record<string, string> = {\n${body}\n};\n`,
);
console.log('icons:', Object.keys(out).length);
